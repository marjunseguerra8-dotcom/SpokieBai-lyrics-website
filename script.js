playbackSpeed.addEventListener("change", () => {
  audio.playbackRate = Number(playbackSpeed.value);
});

let currentIndex = -1;
let shuffle = false;
let repeat = false;
let activeLyrics = [];

function renderTracks(list = tracks) {
  trackGrid.innerHTML = "";

  list.forEach((track) => {
    const index = tracks.indexOf(track);
    const card = document.createElement("article");
    card.className = "track-card";

    const cover = document.createElement("img");
    cover.className = "cover";
    cover.src = track.cover || "images/default.jpg";
    cover.alt = `Album cover for ${track.title}`;
    cover.onerror = () => {
      cover.onerror = null;
      cover.src = "images/default.jpg";
    };

    const title = document.createElement("h3");
    title.textContent = track.title;

    const artist = document.createElement("p");
    artist.textContent = track.artist;

    const button = document.createElement("button");
    button.className = "card-play";
    button.type = "button";
    button.textContent = "▶";
    button.setAttribute("aria-label", `Play ${track.title}`);
    button.addEventListener("click", () => playTrack(index));

    card.append(cover, title, artist, button);
    trackGrid.append(card);
  });

  document.querySelector("#trackCount").textContent =
    `${list.length} ${list.length === 1 ? "track" : "tracks"}`;

  document.querySelector("#emptyState").hidden = list.length !== 0;
}

function showLyrics(track) {
  document.querySelector("#lyricsTitle").textContent = track.title;
  lyricsPanel.hidden = false;
  lyricsLines.innerHTML = "";
  activeLyrics = track.lyrics || [];

  if (!activeLyrics.length) {
    const message = document.createElement("p");
    message.className = "lyric-line active";
    message.textContent = "Lyrics aren’t available for this track yet.";
    lyricsLines.append(message);
    return;
  }

  activeLyrics.forEach((line) => {
    const element = document.createElement("p");
    element.className = "lyric-line";
    element.textContent = line.text;
    lyricsLines.append(element);
  });

  updateLyrics();
}

function updateLyrics() {
  if (!activeLyrics.length) return;

  let activeIndex = -1;

  for (let i = 0; i < activeLyrics.length; i++) {
    if (audio.currentTime >= activeLyrics[i].time) {
      activeIndex = i;
    } else {
      break;
    }
  }

  const elements = lyricsLines.querySelectorAll(".lyric-line");

  elements.forEach((element, index) => {
    element.classList.toggle("active", index === activeIndex);
  });

  if (activeIndex >= 0) {
    elements[activeIndex].scrollIntoView({
      behavior: "smooth",
      block: "center"
    });
  }
}

function playTrack(index) {
  currentIndex = index;
  const track = tracks[currentIndex];

  audio.src = `songs/${track.file}`;

  document.querySelector("#playerTitle").textContent = track.title;
  document.querySelector("#playerArtist").textContent = track.artist;

  playerCover.src = track.cover || "images/default.jpg";
  playerCover.alt = `Album cover for ${track.title}`;
  playerCover.onerror = () => {
    playerCover.onerror = null;
    playerCover.src = "images/default.jpg";
  };

  showLyrics(track);

  audio.play().catch(() => {
    playButton.textContent = "▶";
    playButton.setAttribute("aria-label", "Play");
    alert(
      `Couldn't play "${track.file}". Siguraduhing nasa "songs" folder ang MP3 at tama ang filename.`
    );
  });
}

function togglePlay() {
  if (currentIndex === -1) {
    playTrack(0);
  } else if (audio.paused) {
    audio.play().catch(() => {
      alert("Hindi ma-play ang kanta. Tingnan kung tama ang MP3 file path.");
    });
  } else {
    audio.pause();
  }
}

function nextTrack() {
  if (!tracks.length) return;

  const nextIndex = shuffle
    ? Math.floor(Math.random() * tracks.length)
    : (currentIndex + 1) % tracks.length;

  playTrack(nextIndex);
}

function previousTrack() {
  if (!tracks.length) return;

  if (audio.currentTime > 3) {
    audio.currentTime = 0;
    return;
  }

  const previousIndex =
    currentIndex <= 0 ? tracks.length - 1 : currentIndex - 1;

  playTrack(previousIndex);
}

function formatTime(seconds) {
  if (!Number.isFinite(seconds)) return "0:00";

  const minutes = Math.floor(seconds / 60);
  const remainder = Math.floor(seconds % 60).toString().padStart(2, "0");

  return `${minutes}:${remainder}`;
}

playButton.addEventListener("click", togglePlay);

